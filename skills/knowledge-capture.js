  /**
   * Generate a Changelog from decisions
   * @param {Array} decisions - Decision entries
   * @param {Object} options - Generation options
   * @returns {Object} Generated changelog
   */
  generateChangelog(decisions, options = {}) {
    const timestamp = new Date().toISOString();

    // Group decisions by date (month)
    const grouped = {};
    for (const decision of decisions) {
      const date = new Date(decision.metadata?.createdAt || decision.timestamp);
      const monthKey = `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}`;
      if (!grouped[monthKey]) {
        grouped[monthKey] = [];
      }
      grouped[monthKey].push(decision);
    }

    // Sort months descending
    const sortedMonths = Object.keys(grouped).sort().reverse();

    let content = `# Changelog

> Generated from Knowledge System decisions
> Last updated: ${timestamp.split('T')[0]}

`;

    for (const monthKey of sortedMonths) {
      const [year, month] = monthKey.split('-');
      const monthName = new Date(year, parseInt(month) - 1).toLocaleString('default', { month: 'long' });

      content += `## ${monthName} ${year}\n\n`;

      for (const decision of grouped[monthKey]) {
        const date = new Date(decision.metadata?.createdAt || decision.timestamp);
        const dateStr = date.toISOString().split('T')[0];
        const domain = decision.domain ? `[${decision.domain}]` : '';

        content += `### ${dateStr} ${domain}\n\n`;
        content += `**${decision.title}**\n\n`;

        if (decision.content?.choice || decision.content?.decision) {
          content += `${decision.content.choice || decision.content.decision}\n\n`;
        }

        if (decision.content?.rationale) {
          content += `*Rationale*: ${decision.content.rationale}\n\n`;
        }

        content += `---\n\n`;
      }
    }

    content += `\n*Generated from Knowledge System*`;

    return {
      type: 'changelog',
      title: 'Changelog',
      content: content,
      filePath: options.output || 'CHANGELOG.md',
      generatedAt: timestamp,
      decisionsIncluded: decisions.length
    };
  }

