  /**
   * Capture a decision in real-time during execution
   * @param {Object} decision - Decision data from agent execution
   * @returns {Object} Captured decision with metadata
   */
  captureDecisionRealtime(decision) {
    const timestamp = new Date().toISOString();

    const captured = {
      id: this.generateRealtimeId('dec'),
      type: 'decision',
      timestamp: timestamp,
      title: decision.title || decision.summary,
      summary: decision.summary || decision.title,
      status: decision.status || 'accepted', // proposed, accepted, deprecated, superseded
      content: {
        choice: decision.choice || decision.decision,
        rationale: decision.rationale,
        alternatives: decision.alternatives || [],
        consequences: decision.consequences || [],
        tradeoffs: decision.tradeoffs || null,
        reversible: decision.reversible !== false
      },
      context: {
        trackId: decision.trackId,
        taskId: decision.taskId,
        phase: decision.phase,
        agentId: decision.agentId,
        branch: decision.branch
      },
      domain: decision.domain || this.inferDomainFromDecision(decision),
      tags: decision.tags || this.extractTagsFromDecision(decision),
      confidence: decision.confidence || 0.7,
      importance: decision.importance || 'normal',
      // Review tracking
      reviewDate: decision.reviewDate || null,
      reviewReason: decision.reviewReason || null,
      // Supersession tracking
      supersedes: decision.supersedes || [], // IDs of decisions this replaces
      supersededBy: decision.supersededBy || null, // ID of newer decision that replaces this
      metadata: {
        createdAt: timestamp,
        updatedAt: timestamp,
        source: 'realtime',
        autoExtracted: decision.autoExtracted || false,
        agentOutput: decision.agentOutput ? true : false
      }
    };

    // Add to in-memory collection for session
    this.decisions.push(captured);

    return {
      success: true,
      decision: captured,
      message: `Decision captured: ${captured.title}`
    };
  }

  /**
   * Mark a decision as superseded by a newer decision
   * @param {string} oldDecisionId - ID of decision being superseded
   * @param {string} newDecisionId - ID of the new decision
   * @param {Object} knowledgeStore - KnowledgeStore instance
   * @param {string} branch - Branch name
   * @returns {Object} Update result
   */
  supersedeDecision(oldDecisionId, newDecisionId, knowledgeStore, branch = null) {
    // Update the old decision
    const oldResult = knowledgeStore.update(oldDecisionId, {
      status: 'superseded',
      supersededBy: newDecisionId,
      metadata: {
        updatedAt: new Date().toISOString()
      }
    }, branch);

    if (!oldResult.success) {
      return {
        success: false,
        error: oldResult.error,
        message: `Failed to mark decision as superseded: ${oldResult.message}`
      };
    }

    // Update the new decision to reference what it supersedes
    const newDecision = knowledgeStore.get(newDecisionId, branch);
    if (newDecision) {
      const supersedes = newDecision.supersedes || [];
      if (!supersedes.includes(oldDecisionId)) {
        supersedes.push(oldDecisionId);
        knowledgeStore.update(newDecisionId, {
          supersedes: supersedes
        }, branch);
      }
    }

    return {
      success: true,
      oldDecisionId: oldDecisionId,
      newDecisionId: newDecisionId,
      message: `Decision ${oldDecisionId} marked as superseded by ${newDecisionId}`
    };
  }

  /**
   * Set a review date for a decision
   * @param {string} decisionId - Decision ID
   * @param {string} reviewDate - Date string (YYYY-MM-DD)
   * @param {string} reviewReason - Reason for review
   * @param {Object} knowledgeStore - KnowledgeStore instance
   * @param {string} branch - Branch name
   * @returns {Object} Update result
   */
  setDecisionReviewDate(decisionId, reviewDate, reviewReason, knowledgeStore, branch = null) {
    const result = knowledgeStore.update(decisionId, {
      reviewDate: reviewDate,
      reviewReason: reviewReason,
      metadata: {
        updatedAt: new Date().toISOString()
      }
    }, branch);

    if (!result.success) {
      return {
        success: false,
        error: result.error,
        message: `Failed to set review date: ${result.message}`
      };
    }

    return {
      success: true,
      decisionId: decisionId,
      reviewDate: reviewDate,
      reviewReason: reviewReason,
      message: `Review date set for decision ${decisionId}: ${reviewDate}`
    };
  }

  /**
   * Get decisions that need review (review date has passed)
   * @param {Object} knowledgeStore - KnowledgeStore instance
   * @param {string} branch - Branch name
   * @returns {Object} Decisions needing review
   */
  getDecisionsNeedingReview(knowledgeStore, branch = null) {
    const result = knowledgeStore.query({
      type: 'decision',
      fullEntries: true
    }, branch);

    if (!result.success) {
      return {
        success: false,
        decisions: [],
        message: `Failed to query decisions: ${result.message}`
      };
    }

    const now = new Date();
    const needsReview = (result.entries || []).filter(d => {
      if (!d.reviewDate) return false;
      if (d.status === 'superseded' || d.status === 'deprecated') return false;
      return new Date(d.reviewDate) <= now;
    });

    // Sort by review date (oldest first)
    needsReview.sort((a, b) => new Date(a.reviewDate) - new Date(b.reviewDate));

    return {
      success: true,
      decisions: needsReview,
      total: needsReview.length,
      message: `Found ${needsReview.length} decisions needing review`
    };
  }

  /**
   * Get the supersession chain for a decision
   * @param {string} decisionId - Decision ID
   * @param {Object} knowledgeStore - KnowledgeStore instance
   * @param {string} branch - Branch name
   * @returns {Object} Supersession chain
   */
  getSupersessionChain(decisionId, knowledgeStore, branch = null) {
    const chain = {
      ancestors: [], // Decisions this supersedes (going back)
      current: null,
      successors: [] // Decisions that supersede this (going forward)
    };

    const current = knowledgeStore.get(decisionId, branch);
    if (!current) {
      return {
        success: false,
        chain: chain,
        message: `Decision not found: ${decisionId}`
      };
    }

    chain.current = {
      id: current.id,
      title: current.title,
      status: current.status,
      createdAt: current.metadata?.createdAt
    };

    // Get ancestors (what this decision supersedes)
    const getAncestors = (ids) => {
      for (const id of ids || []) {
        const ancestor = knowledgeStore.get(id, branch);
        if (ancestor) {
          chain.ancestors.push({
            id: ancestor.id,
            title: ancestor.title,
            status: ancestor.status,
            createdAt: ancestor.metadata?.createdAt
          });
          // Recursively get older ancestors
          getAncestors(ancestor.supersedes);
        }
      }
    };
    getAncestors(current.supersedes);

    // Get successors (what supersedes this decision)
    const getSuccessors = (id) => {
      const decision = knowledgeStore.get(id, branch);
      if (decision && decision.supersededBy) {
        const successor = knowledgeStore.get(decision.supersededBy, branch);
        if (successor) {
          chain.successors.push({
            id: successor.id,
            title: successor.title,
            status: successor.status,
            createdAt: successor.metadata?.createdAt
          });
          // Recursively get newer successors
          getSuccessors(successor.id);
        }
      }
    };
    getSuccessors(decisionId);

    return {
      success: true,
      chain: chain,
      message: `Found ${chain.ancestors.length} ancestors and ${chain.successors.length} successors`
    };
  }

