  /**
   * Format components section for spec
   */
  formatComponentsSection(entities) {
    if (!entities || entities.length === 0) {
      return 'Components not specified.';
    }

    return entities.map(entity => `
#### ${entity.title || entity.name}

- **Type**: ${entity.entityType || 'Component'}
- **Location**: \`${entity.content?.location || entity.location || 'N/A'}\`
- **Description**: ${entity.content?.description || entity.description || 'No description'}
${entity.content?.responsibilities?.length ? `- **Responsibilities**:\n${entity.content.responsibilities.map(r => `  - ${r}`).join('\n')}` : ''}
${entity.content?.dependencies?.length ? `- **Dependencies**: ${entity.content.dependencies.join(', ')}` : ''}
`).join('\n');
  }

  /**
   * Format decisions section for spec
   */
  formatDecisionsSection(decisions) {
    if (!decisions || decisions.length === 0) {
      return 'No key decisions documented.';
    }

    return decisions.map(d => `
### ${d.id || 'Decision'}: ${d.title}

${d.content?.choice || d.content?.decision || d.summary || 'Decision details not available.'}

${d.content?.rationale ? `*Rationale*: ${d.content.rationale}` : ''}
`).join('\n');
  }

  /**
   * Format API section for spec
   */
  formatAPISection(endpoints) {
    if (!endpoints || endpoints.length === 0) {
      return 'API not specified.';
    }

    let content = '| Endpoint | Method | Description |\n|----------|--------|-------------|\n';

    for (const ep of endpoints) {
      content += `| ${ep.path} | ${ep.method} | ${ep.description || 'N/A'} |\n`;
    }

    return content;
  }

