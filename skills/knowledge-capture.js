  /**
   * Update a TODO status
   * @param {Object} todo - Existing TODO entry
   * @param {string} newStatus - New status
   * @param {Object} updates - Additional updates
   * @returns {Object} Updated TODO
   */
  updateTodoStatus(todo, newStatus, updates = {}) {
    const timestamp = new Date().toISOString();

    const updated = {
      ...todo,
      status: newStatus,
      content: {
        ...todo.content,
        ...updates.content
      },
      metadata: {
        ...todo.metadata,
        updatedAt: timestamp,
        completedAt: newStatus === 'done' ? timestamp : todo.metadata?.completedAt
      }
    };

    if (updates.notes) {
      updated.content.notes = updated.content.notes
        ? `${updated.content.notes}\n\n${timestamp}: ${updates.notes}`
        : `${timestamp}: ${updates.notes}`;
    }

    return {
      success: true,
      todo: updated,
      message: `TODO updated: ${updated.title} → ${newStatus}`
    };
  }

  /**
   * Extract entities from code analysis
   * @param {Object} codeAnalysis - Code analysis result
   * @returns {Array} Extracted entities
   */
  extractEntitiesFromCode(codeAnalysis) {
    const entities = [];

    // Extract services
    if (codeAnalysis.services) {
      for (const service of codeAnalysis.services) {
        entities.push(this.captureEntity({
          name: service.name,
          entityType: 'service',
          description: service.description || `Service: ${service.name}`,
          location: service.path,
          responsibilities: service.methods || [],
          dependencies: service.imports || [],
          autoExtracted: true
        }).entity);
      }
    }

    // Extract components
    if (codeAnalysis.components) {
      for (const component of codeAnalysis.components) {
        entities.push(this.captureEntity({
          name: component.name,
          entityType: 'component',
          description: component.description || `Component: ${component.name}`,
          location: component.path,
          responsibilities: component.props || [],
          dependencies: component.imports || [],
          autoExtracted: true
        }).entity);
      }
    }

    // Extract API endpoints
    if (codeAnalysis.endpoints) {
      for (const endpoint of codeAnalysis.endpoints) {
        entities.push(this.captureEntity({
          name: `${endpoint.method} ${endpoint.path}`,
          entityType: 'api',
          description: endpoint.description || `API endpoint: ${endpoint.method} ${endpoint.path}`,
          location: endpoint.handler,
          interfaces: [{ method: endpoint.method, path: endpoint.path, params: endpoint.params }],
          autoExtracted: true
        }).entity);
      }
    }

    return entities;
  }

  /**
   * Extract TODOs from code comments
   * @param {string} code - Source code
   * @param {Object} context - Context (file path, etc.)
   * @returns {Array} Extracted TODOs
   */
  extractTodosFromCode(code, context = {}) {
    const todos = [];
    const todoPatterns = [
      /\/\/\s*TODO:?\s*(.+)/gi,
      /\/\*\s*TODO:?\s*(.+?)\*\//gi,
      /#\s*TODO:?\s*(.+)/gi,
      /<!--\s*TODO:?\s*(.+?)-->/gi
    ];

    for (const pattern of todoPatterns) {
      let match;
      while ((match = pattern.exec(code)) !== null) {
        const title = match[1].trim();

        // Skip if too short or looks like template
        if (title.length < 5 || title.includes('{{') || title.includes('$')) {
          continue;
        }

        // Infer priority from keywords
        let priority = 'medium';
        if (/urgent|critical|asap|important/i.test(title)) {
          priority = 'high';
        } else if (/maybe|eventually|nice.?to.?have|low/i.test(title)) {
          priority = 'low';
        }

        todos.push(this.captureTodo({
          title: title,
          priority: priority,
          source: 'code-comment',
          location: context.filePath,
          trackId: context.trackId,
          autoExtracted: true
        }).todo);
      }
    }

    return todos;
  }

  /**
   * Format enhanced retrospective with journal data
   * @param {Object} retro - Enhanced retrospective object
   * @returns {string} Formatted markdown
   */
  formatEnhancedRetrospectiveMarkdown(retro) {
    let content = this.formatRetrospectiveMarkdown(retro);

    // Add journal-specific sections
    if (retro.decisions && retro.decisions.length > 0) {
      content += `\n## Key Decisions Made\n\n`;
      for (const decision of retro.decisions.slice(0, 5)) {
        content += `- ${decision}\n`;
      }
    }

    if (retro.discoveries && retro.discoveries.length > 0) {
      content += `\n## Discoveries\n\n`;
      for (const discovery of retro.discoveries.slice(0, 5)) {
        content += `- ${discovery}\n`;
      }
    }

    if (retro.resolvedBlockers && retro.resolvedBlockers.length > 0) {
      content += `\n## Blocker Resolutions\n\n`;
      for (const blocker of retro.resolvedBlockers) {
        content += `### ${blocker.issue}\n`;
        content += `- **Resolution**: ${blocker.resolution}\n`;
        if (blocker.preventionStrategy) {
          content += `- **Prevention**: ${blocker.preventionStrategy}\n`;
        }
        content += '\n';
      }
    }

    if (retro.journalSummary) {
      content += `\n## Session Journal Summary\n\n`;
      content += `- Total Entries: ${retro.journalSummary.entriesCount || 0}\n`;
      content += `- Decisions Captured: ${retro.journalSummary.decisionsCount || 0}\n`;
      content += `- Discoveries Made: ${retro.journalSummary.discoveriesCount || 0}\n`;
    }

    return content;
  }

