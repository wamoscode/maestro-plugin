  /**
   * Convert string to URL-friendly slug
   */
  slugify(text) {
    return (text || 'untitled')
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '')
      .substring(0, 50);
  }
